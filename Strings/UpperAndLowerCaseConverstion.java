import java.util.*; 
public class UpperAndLowerCaseConverstion{ 
   
    public static void main(String args[]){ 
        Scanner sc = new Scanner(System.in);        
        String s = sc.next();                        // s = RamYA
        System.out.println("UpperCase: "+s.toUpperCase());         // s = RAMYA
        System.out.println("LowerCase: "+s.toLowerCase());         // s = ramya
        }

    }

